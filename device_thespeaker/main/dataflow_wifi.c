esp_err_t dataflow_wifi_init(void) {
    if (s_initialized) return ESP_OK;
    s_initialized = true;
    memset(&s_stats, 0, sizeof(s_stats));


    memset(s_client_socks, -1, sizeof(s_client_socks));
    osal_task_config_t task_cfg = {
        .name = "tcp_server",
        .func = tcp_server_task,
        .arg = NULL,
        .stack_size = 6144,
        .priority = OSAL_PRIORITY_NORMAL,
    };
    osal_task_handle_t handle;
    osal_task_create(&task_cfg, &handle);


    return ESP_OK;
}

esp_err_t dataflow_wifi_deinit(void) {
    s_initialized = false;
    s_connected = false;

    if (s_server_sock >= 0) { close(s_server_sock); s_server_sock = -1; }
    for (int i = 0; i < s_client_count; i++) {
        close(s_client_socks[i]);
    }
    s_client_count = 0;

    return ESP_OK;
}

