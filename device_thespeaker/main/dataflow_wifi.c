/* =========================================================================
 * Length-Prefixed Send/Recv Helpers
 *
 * Wire format: [LEN_LO(1)] [LEN_HI(1)] [PAYLOAD(N)]
 * LEN is the length of PAYLOAD only (not including the 2-byte header)
 * ========================================================================= */

/**
 * @brief Send a length-prefixed message
 * @return ESP_OK on success, ESP_FAIL on error (triggers reconnect)
 */
static esp_err_t send_framed(int sock, const uint8_t *data, size_t len) {
    if (sock < 0 || !data || len == 0 || len > 0xFFFF) return ESP_FAIL;

    uint8_t hdr[2];
    hdr[0] = (uint8_t)(len & 0xFF);
    hdr[1] = (uint8_t)((len >> 8) & 0xFF);

    int sent = send(sock, hdr, 2, 0);
    if (sent != 2) {
        s_stats.send_errors++;
        return ESP_FAIL;
    }
    sent = send(sock, data, len, 0);
    if (sent < 0) {
        s_stats.send_errors++;
        return ESP_FAIL;
    }
    s_stats.packets_sent++;
    return ESP_OK;
}

/**
 * @brief Receive exactly `n` bytes (blocking with timeout)
 * @return number of bytes read, or -1 on error, 0 on disconnect
 */
static int recv_exact(int sock, uint8_t *buf, size_t n) {
    size_t total = 0;
    int timeout_retries = 0;
    while (total < n) {
        int r = recv(sock, buf + total, n - total, 0);
        if (r < 0) {
            if (errno == EAGAIN || errno == EWOULDBLOCK) {
                timeout_retries++;
                if (timeout_retries >= 3) {
                    return -1;
                }
                continue;
            }
            return -1;
        }
        if (r == 0) return 0;
        total += r;
        timeout_retries = 0;
    }
    return (int)total;
}

/**
 * @brief Receive one length-prefixed message
 * @param sock     TCP socket
 * @param buf      Output buffer (must be at least DATAFLOW_WIFI_RX_BUF_SIZE)
 * @param max_len  Buffer capacity
 * @return Payload length, 0 on disconnect, -1 on error
 */
static int recv_framed(int sock, uint8_t *buf, size_t max_len) {
    uint8_t hdr[2];
    int r = recv_exact(sock, hdr, 2);
    if (r <= 0) return r;

    uint16_t payload_len = (uint16_t)hdr[0] | ((uint16_t)hdr[1] << 8);
    if (payload_len == 0) return 0;
    if (payload_len > max_len) {
        OSAL_LOGW("Frame too large: %u > %zu, skipping", payload_len, max_len);
        /* Drain the oversized frame to keep stream in sync */
        uint8_t drain[64];
        size_t remaining = payload_len;
        while (remaining > 0) {
            size_t chunk = remaining < sizeof(drain) ? remaining : sizeof(drain);
            r = recv_exact(sock, drain, chunk);
            if (r <= 0) return r;
            remaining -= chunk;
        }
        return -1;
    }

    r = recv_exact(sock, buf, payload_len);
    if (r <= 0) return r;

    s_stats.packets_received++;
    s_stats.last_seen_ms = get_time_ms();
    return (int)payload_len;
}

/* =========================================================================
 * Protocol-Aware Frame Dispatch
 *
 * After receiving a length-prefixed message, determine whether it's:
 *   1. A frame-descriptor exchange (magic bytes DF_DESC_MAGIC_0/1)
 *   2. A protocol frame (starts with df_wire_header_t, 5+ bytes)
 *   3. A legacy raw message (old format: [var_id_len][var_id][float])
 *
 * Protocol frames are dispatched to s_frame_callback if set.
 * Legacy frames are dispatched to s_rx_callback.
 * ========================================================================= */

static void dispatch_received_message(const uint8_t *data, size_t len) {
    if (len == 0) return;

#if DATAFLOW_WIFI_HAS_DESCRIPTORS
    /* Check for frame descriptor exchange (magic bytes) */
    if (len >= 2 && data[0] == DF_DESC_MAGIC_0 && data[1] == DF_DESC_MAGIC_1) {
        df_frame_descriptor_t remote_desc;
        if (df_descriptor_deserialize(data, len, &remote_desc)) {
#if DATAFLOW_WIFI_HAS_FRAME_DESCS
            const df_frame_descriptor_t *local = df_get_frame_descriptor(remote_desc.frame_id);
            if (local) {
                df_compat_result_t compat = df_descriptor_compare(local, &remote_desc);
                if (compat == DF_COMPAT_BREAKING) {
                    OSAL_LOGE("BREAKING: Peer frame 0x%04X incompatible (hash 0x%08lX vs 0x%08lX)",
                              (unsigned)remote_desc.frame_id,
                              (unsigned long)remote_desc.schema_hash,
                              (unsigned long)local->schema_hash);
                } else {
                    OSAL_LOGI("Peer frame 0x%04X compatible (%s, %d vs %d fields)",
                              (unsigned)remote_desc.frame_id,
                              compat == DF_COMPAT_IDENTICAL ? "identical" :
                              compat == DF_COMPAT_EXTENDED ? "extended" : "subset",
                              remote_desc.field_count, local->field_count);
                }
            } else {
                OSAL_LOGW("Unknown frame ID 0x%04X from peer", (unsigned)remote_desc.frame_id);
                s_stats.unknown_frame_ids++;
            }
#endif
        }
        return;
    }
#endif

#if DATAFLOW_WIFI_HAS_PROTOCOL_DEFS
    /* Try to parse as a protocol frame (requires at least 5 bytes for header) */
    if (len >= DF_WIRE_HEADER_SIZE) {
        df_wire_header_t hdr;
        df_wire_header_decode(data, &hdr);

        /* Sanity check: frame_id must be non-zero and frame_type must be valid */
        if (hdr.frame_id != DF_FRAME_ID_INVALID && hdr.frame_type >= DF_FRAME_TYPE_DATA
            && hdr.frame_type <= DF_FRAME_TYPE_HEARTBEAT) {
            s_stats.protocol_frames_received++;
            if (s_frame_callback) {
                const uint8_t *payload = (len > DF_WIRE_HEADER_SIZE) ? &data[DF_WIRE_HEADER_SIZE] : NULL;
                size_t payload_len = (len > DF_WIRE_HEADER_SIZE) ? (len - DF_WIRE_HEADER_SIZE) : 0;
                s_frame_callback(hdr.frame_id, hdr.frame_type, hdr.sequence, payload, payload_len);
            } else if (s_rx_callback) {
                /* No frame callback set — fall back to raw callback with full data */
                s_rx_callback(data, len);
            }
            return;
        }
        /* If frame_id is 0 or frame_type is invalid, treat as legacy format */
    }
#endif

    /* Legacy format: dispatch to raw callback */
    s_stats.legacy_frames_received++;
    if (s_rx_callback) {
        s_rx_callback(data, len);
    }
}


/* =========================================================================
 * TCP Server Implementation (select-based multiplexed I/O)
 *
 * Uses select() to simultaneously wait for:
 *   - New client connections on the listen socket
 *   - Data from existing clients
 * This prevents half-open connections from blocking new accepts and
 * ensures the server recovers quickly when a client reconnects.
 * ========================================================================= */

static int s_server_sock = -1;
static int s_client_socks[DATAFLOW_WIFI_MAX_CLIENTS];
static uint32_t s_client_last_active[DATAFLOW_WIFI_MAX_CLIENTS];
static int s_client_count = 0;

static void remove_client(int idx) {
    if (idx < 0 || idx >= s_client_count) return;
    close(s_client_socks[idx]);
    s_client_count--;
    s_client_socks[idx] = s_client_socks[s_client_count];
    s_client_last_active[idx] = s_client_last_active[s_client_count];
}

static void handle_new_client(int client_sock) {
    configure_socket_keepalive(client_sock);

    /* If we're at max clients, drop the oldest (likely a stale half-open) */
    if (s_client_count >= DATAFLOW_WIFI_MAX_CLIENTS) {
        OSAL_LOGW("Max clients reached, dropping oldest connection");
        remove_client(0);
    }

    s_client_last_active[s_client_count] = get_time_ms();
    s_client_socks[s_client_count++] = client_sock;
    OSAL_LOGI("New client connected (total: %d)", s_client_count);

#if DATAFLOW_WIFI_HAS_FRAME_DESCS && DATAFLOW_WIFI_HAS_DESCRIPTORS
    {
        uint8_t desc_buf[512];
        for (int di = 0; di < DF_FRAME_COUNT; di++) {
            size_t n = df_descriptor_serialize(g_all_frame_descriptors[di], desc_buf, sizeof(desc_buf));
            if (n > 0) {
                send_framed(client_sock, desc_buf, n);
            }
        }
        OSAL_LOGI("Sent %d frame descriptors to client", DF_FRAME_COUNT);
    }
#endif
}

static void tcp_server_task(void *arg) {
    struct sockaddr_in dest_addr;
    dest_addr.sin_addr.s_addr = htonl(INADDR_ANY);
    dest_addr.sin_family = AF_INET;
    dest_addr.sin_port = htons(DATAFLOW_WIFI_TCP_PORT);

    s_server_sock = socket(AF_INET, SOCK_STREAM, IPPROTO_IP);
    if (s_server_sock < 0) {
        OSAL_LOGE("Unable to create socket");
        osal_task_delete(NULL);
        return;
    }

    int opt = 1;
    setsockopt(s_server_sock, SOL_SOCKET, SO_REUSEADDR, &opt, sizeof(opt));

    if (bind(s_server_sock, (struct sockaddr *)&dest_addr, sizeof(dest_addr)) != 0) {
        OSAL_LOGE("Socket bind failed");
        close(s_server_sock);
        osal_task_delete(NULL);
        return;
    }

    if (listen(s_server_sock, DATAFLOW_WIFI_MAX_CLIENTS) != 0) {
        OSAL_LOGE("Socket listen failed");
        close(s_server_sock);
        osal_task_delete(NULL);
        return;
    }

    OSAL_LOGI("TCP server listening on port %d", DATAFLOW_WIFI_TCP_PORT);
    s_connected = true;

    uint8_t rx_buf[DATAFLOW_WIFI_RX_BUF_SIZE];

    while (s_initialized) {
        fd_set read_fds;
        FD_ZERO(&read_fds);
        FD_SET(s_server_sock, &read_fds);
        int max_fd = s_server_sock;

        for (int i = 0; i < s_client_count; i++) {
            FD_SET(s_client_socks[i], &read_fds);
            if (s_client_socks[i] > max_fd) max_fd = s_client_socks[i];
        }

        struct timeval tv = { .tv_sec = 5, .tv_usec = 0 };
        int ready = select(max_fd + 1, &read_fds, NULL, NULL, &tv);

        if (ready < 0) {
            if (errno == EINTR) continue;
            OSAL_LOGE("select() error: %d", errno);
            osal_task_delay_ms(100);
            continue;
        }

        /* select() timeout — check for per-client stale connections */
        if (ready == 0) {
            uint32_t now = get_time_ms();
            for (int i = s_client_count - 1; i >= 0; i--) {
                if ((now - s_client_last_active[i]) > 30000) {
                    OSAL_LOGW("Client %d inactive for 30s, dropping", i);
                    remove_client(i);
                }
            }
            continue;
        }

        /* Check for new incoming connections */
        if (FD_ISSET(s_server_sock, &read_fds)) {
            struct sockaddr_in source_addr;
            socklen_t addr_len = sizeof(source_addr);
            int new_sock = accept(s_server_sock, (struct sockaddr *)&source_addr, &addr_len);
            if (new_sock >= 0) {
                handle_new_client(new_sock);
            }
        }

        /* Check for data from existing clients */
        for (int i = s_client_count - 1; i >= 0; i--) {
            if (!FD_ISSET(s_client_socks[i], &read_fds)) continue;

            int len = recv_framed(s_client_socks[i], rx_buf, sizeof(rx_buf));
            if (len < 0) {
                OSAL_LOGW("Client %d recv error, disconnecting", i);
                s_stats.recv_errors++;
                remove_client(i);
                continue;
            }
            if (len == 0) {
                OSAL_LOGW("Client %d disconnected (FIN)", i);
                remove_client(i);
                continue;
            }

            s_client_last_active[i] = get_time_ms();
            dispatch_received_message(rx_buf, (size_t)len);
        }

        /* Update connected status based on client count */
        s_connected = (s_client_count > 0) || (s_server_sock >= 0);
    }

    osal_task_delete(NULL);
}


