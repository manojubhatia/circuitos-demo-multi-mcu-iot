esp_err_t dataflow_wifi_send_frame(uint16_t frame_id, uint8_t frame_type,
                                    const uint8_t* payload, size_t payload_len) {
    if (!s_connected) return ESP_FAIL;

    size_t total_len = DF_WIRE_HEADER_SIZE + payload_len;
    if (total_len > 0xFFFF) return ESP_ERR_INVALID_SIZE;

    /* Build wire message: [header(5)][payload(N)] */
    uint8_t msg[DF_WIRE_HEADER_SIZE + 512];
    uint8_t *buf = msg;
    bool heap_alloc = false;

    if (total_len > sizeof(msg)) {
        buf = (uint8_t *)malloc(total_len);
        if (!buf) return ESP_ERR_NO_MEM;
        heap_alloc = true;
    }

    uint16_t seq = s_tx_sequence++;
    df_wire_header_encode(buf, frame_id, seq, frame_type);

    if (payload && payload_len > 0) {
        memcpy(buf + DF_WIRE_HEADER_SIZE, payload, payload_len);
    }

    esp_err_t ret;

    for (int i = 0; i < s_client_count; i++) {
        if (s_client_socks[i] >= 0) {
            if (send_framed(s_client_socks[i], buf, total_len) != ESP_OK) {
                OSAL_LOGW("Frame send to client %d failed, removing", i);
                close(s_client_socks[i]);
                s_client_socks[i] = s_client_socks[--s_client_count];
                i--;
            }
        }
    }
    ret = ESP_OK;


    if (ret == ESP_OK) {
        s_stats.protocol_frames_sent++;
    }
    if (heap_alloc) free(buf);
    return ret;
}

