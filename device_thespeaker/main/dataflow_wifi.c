esp_err_t dataflow_wifi_send(const uint8_t* data, size_t len) {
    if (!s_connected || !data || len == 0) return ESP_FAIL;


    for (int i = 0; i < s_client_count; i++) {
        if (s_client_socks[i] >= 0) {
            if (send_framed(s_client_socks[i], data, len) != ESP_OK) {
                OSAL_LOGW("Send to client %d failed, removing", i);
                close(s_client_socks[i]);
                s_client_socks[i] = s_client_socks[--s_client_count];
                i--;
            }
        }
    }

    return ESP_OK;
}

bool dataflow_wifi_is_connected(void) {
    return s_connected;
}

