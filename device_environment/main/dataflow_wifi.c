esp_err_t dataflow_wifi_init(void) {
    if (s_initialized) return ESP_OK;
    s_initialized = true;
    memset(&s_stats, 0, sizeof(s_stats));


    osal_task_config_t task_cfg = {
        .name = "tcp_client",
        .func = tcp_client_task,
        .arg = NULL,
        .stack_size = 4096,
        .priority = OSAL_PRIORITY_NORMAL,
    };
    osal_task_handle_t handle;
    osal_task_create(&task_cfg, &handle);


    return ESP_OK;
}

esp_err_t dataflow_wifi_deinit(void) {
    s_initialized = false;
    s_connected = false;

    if (s_sock >= 0) { close(s_sock); s_sock = -1; }

    return ESP_OK;
}

