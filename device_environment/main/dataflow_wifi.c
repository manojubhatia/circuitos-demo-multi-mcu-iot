#define DATAFLOW_SERVER_HOST "thespeaker.local"
#define DATAFLOW_RECONNECT_MIN_MS   1000
#define DATAFLOW_RECONNECT_MAX_MS   30000

static bool resolve_server_ip(struct sockaddr_in *dest) {
    memset(dest, 0, sizeof(*dest));
    dest->sin_family = AF_INET;
    dest->sin_port = htons(DATAFLOW_WIFI_TCP_PORT);

    dest->sin_addr.s_addr = inet_addr(DATAFLOW_SERVER_HOST);
    if (dest->sin_addr.s_addr != INADDR_NONE) {
        return true;
    }

    struct addrinfo hints = { .ai_family = AF_INET, .ai_socktype = SOCK_STREAM };
    struct addrinfo *res = NULL;
    int err = getaddrinfo(DATAFLOW_SERVER_HOST, NULL, &hints, &res);
    if (err == 0 && res) {
        struct sockaddr_in *resolved = (struct sockaddr_in *)res->ai_addr;
        dest->sin_addr = resolved->sin_addr;
        OSAL_LOGI("Resolved %s -> %s", DATAFLOW_SERVER_HOST, inet_ntoa(dest->sin_addr));
        freeaddrinfo(res);
        return true;
    }
    if (res) freeaddrinfo(res);
    OSAL_LOGW("Failed to resolve %s", DATAFLOW_SERVER_HOST);
    return false;
}

static void tcp_client_task(void *arg) {
    uint32_t backoff_ms = DATAFLOW_RECONNECT_MIN_MS;

    while (s_initialized) {
        struct sockaddr_in dest_addr;
        if (!resolve_server_ip(&dest_addr)) {
            osal_task_delay_ms(backoff_ms);
            if (backoff_ms < DATAFLOW_RECONNECT_MAX_MS) backoff_ms *= 2;
            continue;
        }

        s_sock = socket(AF_INET, SOCK_STREAM, IPPROTO_IP);
        if (s_sock < 0) {
            OSAL_LOGE("Unable to create socket");
            osal_task_delay_ms(backoff_ms);
            if (backoff_ms < DATAFLOW_RECONNECT_MAX_MS) backoff_ms *= 2;
            continue;
        }

        /* Set a connect timeout to avoid blocking forever */
        struct timeval conn_tv = { .tv_sec = 5, .tv_usec = 0 };
        setsockopt(s_sock, SOL_SOCKET, SO_SNDTIMEO, &conn_tv, sizeof(conn_tv));

        if (connect(s_sock, (struct sockaddr *)&dest_addr, sizeof(dest_addr)) != 0) {
            OSAL_LOGW("Connection failed to %s:%d, retrying in %lums...",
                          DATAFLOW_SERVER_HOST, DATAFLOW_WIFI_TCP_PORT, (unsigned long)backoff_ms);
            close(s_sock);
            s_sock = -1;
            osal_task_delay_ms(backoff_ms);
            if (backoff_ms < DATAFLOW_RECONNECT_MAX_MS) backoff_ms *= 2;
            continue;
        }

        s_connected = true;
        backoff_ms = DATAFLOW_RECONNECT_MIN_MS;
        s_stats.reconnect_count++;
        OSAL_LOGI("Connected to server on port %d", DATAFLOW_WIFI_TCP_PORT);

        configure_socket_keepalive(s_sock);

#if DATAFLOW_WIFI_HAS_FRAME_DESCS && DATAFLOW_WIFI_HAS_DESCRIPTORS
        {
            uint8_t desc_buf[512];
            for (int di = 0; di < DF_FRAME_COUNT; di++) {
                size_t n = df_descriptor_serialize(g_all_frame_descriptors[di], desc_buf, sizeof(desc_buf));
                if (n > 0) {
                    send_framed(s_sock, desc_buf, n);
                }
            }
            OSAL_LOGI("Sent %d frame descriptors to server", DF_FRAME_COUNT);
        }
#endif

        uint8_t rx_buf[DATAFLOW_WIFI_RX_BUF_SIZE];
        int consecutive_timeouts = 0;

        while (s_initialized && s_connected) {
            int len = recv_framed(s_sock, rx_buf, sizeof(rx_buf));
            if (len < 0) {
                if (errno == EAGAIN || errno == EWOULDBLOCK) {
                    consecutive_timeouts++;
                    /* After 6 consecutive timeouts (~60s with 10s recv timeout),
                       force reconnect — the connection is likely dead */
                    if (consecutive_timeouts >= 6) {
                        OSAL_LOGW("No data for ~%ds, forcing reconnect",
                                  consecutive_timeouts * 10);
                        s_connected = false;
                        break;
                    }
                    continue;
                }
                s_connected = false;
                s_stats.recv_errors++;
                break;
            }
            if (len == 0) {
                s_connected = false;
                break;
            }

            consecutive_timeouts = 0;
            dispatch_received_message(rx_buf, (size_t)len);
        }

        close(s_sock);
        s_sock = -1;
        s_connected = false;
        OSAL_LOGW("Disconnected, reconnecting in %lums...", (unsigned long)backoff_ms);
        osal_task_delay_ms(backoff_ms);
        if (backoff_ms < DATAFLOW_RECONNECT_MAX_MS) backoff_ms *= 2;
    }

    osal_task_delete(NULL);
}


