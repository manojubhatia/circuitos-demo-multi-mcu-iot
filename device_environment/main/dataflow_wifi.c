esp_err_t dataflow_wifi_send(const uint8_t* data, size_t len) {
    if (!s_connected || !data || len == 0) return ESP_FAIL;


    if (s_sock >= 0) {
        if (send_framed(s_sock, data, len) != ESP_OK) {
            OSAL_LOGW("Send failed, triggering reconnect");
            s_connected = false;
            return ESP_FAIL;
        }
    }

    return ESP_OK;
}

bool dataflow_wifi_is_connected(void) {
    return s_connected;
}

