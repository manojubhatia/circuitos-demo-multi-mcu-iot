#!/usr/bin/env python3
"""
Serial Bridge: Reads sensor data from theSpeaker (3 boards) device and posts to backend.
Generated by Embedded Generator

This script bridges serial output from the device to the HTTP backend,
enabling real-time data streaming to the frontend dashboard.

Usage:
    python3 serial_bridge.py [--port PORT] [--backend URL]

Default port: /dev/ttyUSB0
Default backend: http://localhost:8500/api/data
"""

import serial
import requests
import re
import time
import sys
import argparse
from datetime import datetime

# Configuration
DEFAULT_PORT = "/dev/ttyUSB0"
BAUD_RATE = 115200
BACKEND_URL = "http://localhost:8500/api/data"

# Sensor data patterns - auto-generated from project signals
PATTERNS = [
    (re.compile(r'temperature[=:]\s*([\d.]+)', re.IGNORECASE), 'temperature', float),
    (re.compile(r'humidity[=:]\s*([\d.]+)', re.IGNORECASE), 'humidity', float),
    # Generic temperature/humidity patterns (fallback)
    (re.compile(r'Temp[erature]*[=:]\s*([\d.]+)', re.IGNORECASE), 'aht20_data_temperature', float),
    (re.compile(r'Hum[idity]*[=:]\s*([\d.]+)', re.IGNORECASE), 'aht20_data_humidity', float),
]


def parse_line(line: str) -> dict:
    """Parse a serial line and extract sensor values."""
    data = {}
    for pattern, key, converter in PATTERNS:
        match = pattern.search(line)
        if match:
            try:
                data[key] = converter(match.group(1))
            except (ValueError, IndexError):
                pass
    return data


def find_serial_port() -> str:
    """Auto-detect serial port."""
    import glob
    import os
    
    # Try default/udev symlink first
    if os.path.exists(DEFAULT_PORT):
        return DEFAULT_PORT
    
    # Try common serial ports
    candidates = glob.glob('/dev/ttyUSB*') + glob.glob('/dev/ttyACM*')
    if candidates:
        return sorted(candidates)[0]
    
    return DEFAULT_PORT


def main():
    parser = argparse.ArgumentParser(description='Serial to HTTP bridge for theSpeaker (3 boards)')
    parser.add_argument('--port', '-p', default=None, help=f'Serial port (default: auto-detect or {DEFAULT_PORT})')
    parser.add_argument('--backend', '-b', default=BACKEND_URL, help=f'Backend URL (default: {BACKEND_URL})')
    parser.add_argument('--verbose', '-v', action='store_true', help='Verbose output')
    args = parser.parse_args()
    
    port = args.port or find_serial_port()
    backend_url = args.backend
    
    print(f"Serial Bridge: {port} -> {backend_url}")
    print(f"Baud rate: {BAUD_RATE}")
    print("-" * 50)
    
    try:
        ser = serial.Serial(port, BAUD_RATE, timeout=1)
        print(f"Connected to {port}")
    except serial.SerialException as e:
        print(f"ERROR: Failed to open serial port {port}: {e}")
        print("\nTroubleshooting:")
        print("  1. Check device is connected")
        print("  2. Check port permissions: sudo chmod 666 " + port)
        print("  3. Try a different port with --port=/dev/ttyUSB0")
        sys.exit(1)
    
    count = 0
    errors = 0
    last_post_time = 0
    min_interval = 0.1  # Minimum 100ms between posts
    
    print("\nListening for sensor data... (Ctrl+C to stop)")
    
    while True:
        try:
            line = ser.readline().decode('utf-8', errors='ignore').strip()
            if not line:
                continue
            
            if args.verbose:
                print(f"RAW: {line}")
            
            data = parse_line(line)
            if not data:
                continue
            
            # Rate limiting
            now = time.time()
            if now - last_post_time < min_interval:
                continue
            last_post_time = now
            
            # Add MCU identifier
            data['mcu_id'] = 'board_0'
            
            try:
                resp = requests.post(backend_url, json=data, timeout=2)
                count += 1
                
                if count % 10 == 0:  # Print every 10th reading
                    values = ' '.join(f"{k}={v}" for k, v in data.items() if k != 'mcu_id')
                    print(f"[{count}] {values} -> HTTP {resp.status_code}")
                    
            except requests.RequestException as e:
                errors += 1
                if errors % 10 == 0:
                    print(f"WARNING: {errors} POST errors (last: {e})")
        
        except KeyboardInterrupt:
            print(f"\n\nStopped. Sent {count} readings, {errors} errors.")
            break
        except Exception as e:
            print(f"Error: {e}")
            time.sleep(0.5)
    
    ser.close()


if __name__ == "__main__":
    main()
