"""
Command Dispatcher — Transport-agnostic command delivery to devices.

Routes commands from the frontend/API to devices via the appropriate transport:
- WiFi: HTTP POST to device's /cmd endpoint
- UART/Serial: JSON line over serial port
- BLE: GATT write to command characteristic

Device addresses are learned from:
1. Telemetry data (device IP in HTTP headers / WebSocket origin)
2. mDNS service discovery
3. Heartbeat registration

Auto-generated by embedOS.
"""

import asyncio
import json
from typing import Dict, Optional, Any, Tuple
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from enum import Enum
from loguru import logger

try:
    import httpx
    HTTPX_AVAILABLE = True
except ImportError:
    HTTPX_AVAILABLE = False


class TransportType(Enum):
    HTTP = "http"
    SERIAL = "serial"
    BLE = "ble"
    UNKNOWN = "unknown"


@dataclass
class DeviceRecord:
    """Tracks a known device and how to reach it."""
    mcu_id: str
    transport: TransportType
    address: str = ""
    port: int = 8501
    last_seen: datetime = field(default_factory=datetime.utcnow)
    serial_port: str = ""


class CommandDispatcher:
    """
    Routes commands to devices via the correct transport.

    Usage:
        dispatcher = CommandDispatcher()
        dispatcher.register_device("board_0", "http", "192.168.0.42", 8501)
        await dispatcher.dispatch("board_0", {"type": "set_output", ...})
    """

    def __init__(self, default_cmd_port: int = 8501):
        self._devices: Dict[str, DeviceRecord] = {}
        self._default_cmd_port = default_cmd_port
        self._serial_receivers = {}
        self._http_client: Optional[Any] = None
        self._stale_threshold = timedelta(minutes=5)

    def register_device(
        self,
        mcu_id: str,
        transport: str = "http",
        address: str = "",
        port: int = 0,
        serial_port: str = "",
    ):
        """Register or update a device's transport info."""
        transport_enum = TransportType(transport) if transport in TransportType.__members__.values() else TransportType.HTTP
        try:
            transport_enum = TransportType(transport)
        except ValueError:
            transport_enum = TransportType.HTTP

        self._devices[mcu_id] = DeviceRecord(
            mcu_id=mcu_id,
            transport=transport_enum,
            address=address,
            port=port or self._default_cmd_port,
            serial_port=serial_port,
        )
        logger.info(f"Device registered: {mcu_id} via {transport_enum.value} "
                     f"@ {address}:{port or self._default_cmd_port}")

    def register_from_telemetry(self, mcu_id: str, remote_ip: str):
        """Auto-register a device when we see telemetry from it."""
        existing = self._devices.get(mcu_id)
        if existing:
            existing.address = remote_ip
            existing.last_seen = datetime.utcnow()
        else:
            self.register_device(mcu_id, "http", remote_ip)

    def set_serial_receiver(self, receiver):
        """Register a serial receiver for UART-based command delivery."""
        self._serial_receivers[id(receiver)] = receiver

    @property
    def known_devices(self) -> Dict[str, DeviceRecord]:
        return dict(self._devices)

    async def dispatch(self, mcu_id: str, command: dict) -> bool:
        """Send a command to a specific device. Returns True if delivered."""
        device = self._devices.get(mcu_id)
        if not device:
            logger.warning(f"No known device '{mcu_id}' — cannot dispatch command")
            return False

        if device.transport == TransportType.HTTP:
            return await self._dispatch_http(device, command)
        elif device.transport == TransportType.SERIAL:
            return await self._dispatch_serial(device, command)
        elif device.transport == TransportType.BLE:
            return await self._dispatch_ble(device, command)
        else:
            logger.warning(f"Unsupported transport for {mcu_id}: {device.transport}")
            return False

    async def dispatch_broadcast(self, command: dict) -> int:
        """Send a command to ALL known devices. Returns count delivered."""
        if not self._devices:
            logger.warning("dispatch_broadcast: no devices registered yet — command dropped")
            return 0
        delivered = 0
        for mcu_id in list(self._devices.keys()):
            if await self.dispatch(mcu_id, command):
                delivered += 1
        return delivered

    async def _dispatch_http(self, device: DeviceRecord, command: dict) -> bool:
        """Send command via HTTP POST to device's /cmd endpoint."""
        if not device.address:
            logger.warning(f"No IP address for {device.mcu_id}")
            return False

        url = f"http://{device.address}:{device.port}/cmd"
        try:
            if HTTPX_AVAILABLE:
                if not self._http_client:
                    self._http_client = httpx.AsyncClient(timeout=5.0)
                resp = await self._http_client.post(url, json=command)
                ok = resp.status_code == 200
            else:
                import aiohttp
                async with aiohttp.ClientSession() as session:
                    async with session.post(url, json=command, timeout=aiohttp.ClientTimeout(total=5)) as resp:
                        ok = resp.status == 200

            if ok:
                logger.debug(f"Command delivered to {device.mcu_id} via HTTP: {command.get('variable_id', '?')}")
            else:
                logger.warning(f"HTTP command to {device.mcu_id} failed: status {resp.status_code if HTTPX_AVAILABLE else resp.status}")
            return ok

        except Exception as e:
            logger.error(f"HTTP dispatch to {device.mcu_id} ({url}) failed: {e}")
            return False

    async def _dispatch_serial(self, device: DeviceRecord, command: dict) -> bool:
        """Send command as newline-delimited JSON over serial."""
        json_line = json.dumps(command) + "\n"
        data = json_line.encode("utf-8")

        for receiver in self._serial_receivers.values():
            if hasattr(receiver, "send_to_mcu"):
                try:
                    ok = await receiver.send_to_mcu(device.mcu_id, data)
                    if ok:
                        logger.debug(f"Command delivered to {device.mcu_id} via serial")
                        return True
                except Exception as e:
                    logger.error(f"Serial dispatch to {device.mcu_id} failed: {e}")

        logger.warning(f"No serial receiver can reach {device.mcu_id}")
        return False

    async def _dispatch_ble(self, device: DeviceRecord, command: dict) -> bool:
        """Send command via BLE GATT write (placeholder — extend with BLE receiver)."""
        logger.warning(f"BLE dispatch to {device.mcu_id} not yet implemented")
        return False

    async def dispatch_stream_control(
        self, mcu_id: str, variable_id: str, action: str
    ) -> bool:
        """
        Send a protocol-aware stream control command to a device.
        
        Resolves the variable_id to a frame_id using the protocol decoder,
        then dispatches a begin_stream / stop_stream command with both
        the variable_id and frame_id so the device can use either.
        
        Args:
            mcu_id: Target device ID
            variable_id: Variable to start/stop streaming
            action: "begin_stream" or "stop_stream"
        """
        frame_id = None
        try:
            from protocol_decoder import get_frame_ids_for_variable
            frame_ids = get_frame_ids_for_variable(variable_id)
            if frame_ids:
                frame_id = frame_ids[0]
                logger.info(f"Resolved {variable_id} -> frame_id 0x{frame_id:04X} for {action}")
        except ImportError:
            logger.debug("protocol_decoder not available, sending without frame_id")
        
        command = {
            "type": action,
            "variable_id": variable_id,
        }
        if frame_id is not None:
            command["frame_id"] = frame_id
        
        return await self.dispatch(mcu_id, command)

    async def close(self):
        """Clean up resources."""
        if self._http_client and HTTPX_AVAILABLE:
            await self._http_client.aclose()
            self._http_client = None